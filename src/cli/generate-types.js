"use strict";

/**
 * Maps a db-model-router column rule string to a TypeScript type.
 *
 * Rules follow the pattern:
 * [required|]<type>[:<subtype>][|<validator>...]
 *
 * Examples:
 * - "auto_increment" -> { type: "number", required: true }
 * - "required|string" -> { type: "string", required: true }
 * - "string:text" -> { type: "string", required: false }
 * - "integer" -> { type: "number", required: false }
 * - "boolean" -> { type: "boolean", required: false }
 * - "datetime" -> { type: "string | Date", required: false }
 * - "object" -> { type: "Record<string, any>", required: false }
 */
function ruleToTypeScript(ruleString) {
  if (typeof ruleString !== "string") {
    return { type: "any", required: false };
  }

  const parts = ruleString.split("|");
  let isRequired = false;
  let typePart = "";

  for (const part of parts) {
    if (part === "required") {
      isRequired = true;
    } else if (!typePart && !part.includes(":") && isKnownType(part)) {
      typePart = part;
    } else if (!typePart && part.includes(":")) {
      typePart = part.split(":")[0];
    }
  }

  if (!typePart && parts.length > 0) {
    // Fallback: take first part that isn't required
    typePart = parts.find((p) => p !== "required")?.split(":")[0] || "string";
  }

  let tsType;
  switch (typePart.toLowerCase()) {
    case "auto_increment":
      tsType = "number";
      isRequired = true;
      break;
    case "integer":
    case "numeric":
    case "number":
    case "float":
    case "double":
    case "decimal":
      tsType = "number";
      break;
    case "boolean":
    case "bool":
      tsType = "boolean";
      break;
    case "datetime":
    case "timestamp":
    case "date":
      tsType = "string | Date";
      break;
    case "object":
    case "json":
    case "jsonb":
      tsType = "Record<string, any>";
      break;
    case "array":
      tsType = "any[]";
      break;
    case "string":
    case "text":
    default:
      tsType = "string";
      break;
  }

  return { type: tsType, required: isRequired };
}

function isKnownType(str) {
  const known = [
    "auto_increment",
    "string",
    "integer",
    "numeric",
    "boolean",
    "datetime",
    "object",
    "array",
  ];
  return known.includes(str.toLowerCase());
}

/**
 * Convert snake_case or plural table name to PascalCase interface name.
 * e.g., "users" -> "User", "order_items" -> "OrderItem"
 */
function toPascalCase(str) {
  return str
    .split("_")
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join("");
}

/**
 * Generate TypeScript definitions from a dbmr.schema.json object.
 *
 * @param {object} schema Parsed schema object with `tables` dictionary
 * @returns {string} TypeScript declaration file content
 */
function generateTypes(schema) {
  if (!schema || !schema.tables || typeof schema.tables !== "object") {
    throw new Error("Invalid schema: missing 'tables' definition");
  }

  const lines = [
    "// Auto-generated by db-model-router types",
    "// Do not edit this file directly.",
    "",
    'import type { ModelInstance } from "db-model-router";',
    "",
  ];

  const tableEntries = Object.entries(schema.tables);

  for (const [tableName, tableDef] of tableEntries) {
    const interfaceName = toPascalCase(tableName);
    lines.push(`export interface ${interfaceName} {`);

    const columns = tableDef.columns || {};
    for (const [colName, colRule] of Object.entries(columns)) {
      const { type, required } = ruleToTypeScript(colRule);
      const safeColName =
        colName.includes(".") || !/^[a-zA-Z_$][a-zA-Z0-9_$]*$/.test(colName)
          ? `"${colName}"`
          : colName;
      if (required) {
        lines.push(`  ${safeColName}: ${type};`);
      } else {
        lines.push(`  ${safeColName}?: ${type} | null;`);
      }
    }

    lines.push("}");
    lines.push("");
  }

  // Generate DatabaseSchema map
  lines.push("export interface DatabaseSchema {");
  for (const [tableName] of tableEntries) {
    const interfaceName = toPascalCase(tableName);
    lines.push(`  "${tableName}": ${interfaceName};`);
  }
  lines.push("}");
  lines.push("");

  lines.push("export type TableName = keyof DatabaseSchema;");
  lines.push("");
  lines.push(
    "export type TypedModel<T extends TableName> = ModelInstance<DatabaseSchema[T]>;",
  );
  lines.push("");

  return lines.join("\n");
}

module.exports = {
  generateTypes,
  ruleToTypeScript,
  toPascalCase,
};
