"use strict";

const assert = require("assert");
const oracleDb = require("../../src/oracle/db");
const mssqlDb = require("../../src/mssql/db");

describe("Enterprise Database Adapters Coverage (Oracle & MSSQL)", function () {
  this.timeout(25000);

  // -------------------------------------------------------------------------
  // 1. Oracle Adapter Coverage
  // -------------------------------------------------------------------------
  describe("Oracle Adapter", function () {
    const testTable = ("t_ora_" + Date.now()).slice(0, 28).toUpperCase();

    before(async function () {
      oracleDb.connect({
        host: "localhost",
        port: 1521,
        database: "freepdb1",
        user: "system",
        password: "oracle",
        dateStrings: true,
      });

      await oracleDb.query(`
        CREATE TABLE "${testTable}" (
          "ID" NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          "NAME" VARCHAR2(255) NOT NULL,
          "SCORE" NUMBER DEFAULT 0,
          "IS_DELETED" NUMBER DEFAULT 0
        )
      `);
    });

    after(async function () {
      try {
        await oracleDb.query(`DROP TABLE "${testTable}"`);
      } finally {
        await oracleDb.disconnect();
      }
    });

    it("escapeId, sort_builder, and where edge cases", function () {
      assert.strictEqual(oracleDb.escapeId("users"), '"USERS"');
      assert.strictEqual(oracleDb.escapeId("schema.users"), '"SCHEMA"."USERS"');

      assert.deepStrictEqual(oracleDb.sort_builder(null), { query: "", value: [] });
      assert.deepStrictEqual(oracleDb.sort_builder([]), { query: "", value: [] });
      assert.strictEqual(oracleDb.sort_builder(["NAME"]).query, 'ORDER BY "NAME" ASC');
      assert.strictEqual(oracleDb.sort_builder(["-SCORE", "+NAME"]).query, 'ORDER BY "SCORE" DESC,"NAME" ASC');

      assert.strictEqual(oracleDb.where("invalid"), null);
      assert.deepStrictEqual(oracleDb.where([]), { query: "", value: [] });

      const sd = oracleDb.where([], "IS_DELETED");
      assert.ok(sd.query.includes('"IS_DELETED" = :1'));
      assert.strictEqual(sd.value[0], 0);

      const w = oracleDb.where([
        [
          ["NAME", "=", "Oracle User"],
          ["SCORE", ">", 10],
          ["SCORE", "<", 100],
          ["SCORE", "<=", 90],
          ["SCORE", ">=", 20],
          ["SCORE", "!=", 50],
          ["NAME", "like", "Oracle"],
          ["NAME", "not like", "Test"],
          ["SCORE", "in", [1, 2]],
          ["SCORE", "not in", [3, 4]],
          ["IS_DELETED", "=", true],
          ["NAME", "=", ""],
        ],
      ]);
      assert.ok(w.query.startsWith("WHERE (("));
      assert.strictEqual(oracleDb.where([[["NAME", "INVALID_OP", "val"]]]), null);
      assert.strictEqual(oracleDb.where([[["NAME", "in", "not-array"]]]), null);
    });

    it("CRUD operations: insert, list, get, qcount, upsert, remove", async function () {
      // 1. Single insert
      const insRes = await oracleDb.insert(testTable, { NAME: "Oracle Alice", SCORE: 85 });
      assert.ok(insRes.id > 0);
      assert.strictEqual(insRes.rows, 1);
      const insertedId = insRes.id;

      // 2. Bulk insert
      const bulkRes = await oracleDb.insert(testTable, [
        { NAME: "Oracle Bob", SCORE: 90 },
        { NAME: "Oracle Charlie", SCORE: 70 },
      ]);
      assert.strictEqual(bulkRes.rows, 2);

      // 3. Upsert
      const upRes = await oracleDb.upsert(testTable, { ID: insertedId, NAME: "Oracle Alice Up", SCORE: 95 }, ["ID"]);
      assert.ok(upRes.rows >= 0);

      // 4. List
      const listRes = await oracleDb.list(testTable, [[["SCORE", ">=", 70]]], ["-SCORE"], null, 0, 10);
      assert.ok(listRes.data.length >= 3);
      assert.strictEqual(listRes.count, 3);

      // 5. Get
      const getRes = await oracleDb.get(testTable, [[["ID", "=", insertedId]]]);
      assert.strictEqual(getRes.data.length, 1);

      // 6. Qcount
      const countRes = await oracleDb.qcount(testTable, [[["SCORE", ">=", 70]]]);
      assert.strictEqual(countRes, 3);

      // 7. Soft remove
      const softRem = await oracleDb.remove(testTable, [[["ID", "=", insertedId]]], "IS_DELETED");
      assert.ok(softRem.message.includes("removed"));

      // 8. Hard remove
      const hardRem = await oracleDb.remove(testTable, [[["ID", "=", insertedId]]]);
      assert.ok(hardRem.message.includes("removed"));

      // 9. Pure upsert (no unique keys)
      const pureUp = await oracleDb.upsert(testTable, { NAME: "Oracle Pure", SCORE: 55 }, []);
      assert.strictEqual(pureUp.rows, 1);

      // 10. Upsert with missing keys fallback to UPDATE (using lowercase id matching getPkColumn)
      const listOne = await oracleDb.list(testTable, [[["NAME", "=", "Oracle Bob"]]]);
      const bobId = listOne.data[0].ID;
      const fallbackUp = await oracleDb.upsert(testTable, { id: bobId, SCORE: 999 }, ["NONEXISTENT"]);
      assert.ok(fallbackUp.rows >= 1);

      // 11. _mergeInsertOnly via insert(table, data, uniqueKeys)
      const mergeIns = await oracleDb.insert(
        testTable,
        [
          { NAME: "Ora Batch 1", SCORE: 11 },
          { NAME: "Ora Batch 2", SCORE: 22 },
        ],
        ["NAME"],
      );
      assert.strictEqual(mergeIns.rows, 2);

      // Single insert with uniqueKeys (exercises total === 1 pk fetch in merge)
      const singleMerge = await oracleDb.insert(
        testTable,
        { NAME: "Ora Single Merge", SCORE: 33 },
        ["NAME"],
      );
      assert.strictEqual(singleMerge.rows, 1);
      assert.ok(singleMerge.id >= 0);

      // 12. getSqlCaptureLog
      const logs = oracleDb.getSqlCaptureLog();
      assert.ok(Array.isArray(logs));
    });
  });

  // -------------------------------------------------------------------------
  // 2. MSSQL Adapter Coverage
  // -------------------------------------------------------------------------
  describe("MSSQL Adapter", function () {
    const testTable = "test_mssql_cov_" + Date.now();

    before(async function () {
      await mssqlDb.connect({
        host: "localhost",
        port: 1433,
        database: "master",
        user: "sa",
        password: "Password123!",
      });

      await mssqlDb.query(`
        IF OBJECT_ID('dbo.[${testTable}]', 'U') IS NOT NULL
          DROP TABLE dbo.[${testTable}];
        CREATE TABLE dbo.[${testTable}] (
          id INT IDENTITY(1,1) PRIMARY KEY,
          name VARCHAR(255) NOT NULL,
          score INT DEFAULT 0,
          is_deleted INT DEFAULT 0
        )
      `);
    });

    after(async function () {
      try {
        await mssqlDb.query(`IF OBJECT_ID('dbo.[${testTable}]', 'U') IS NOT NULL DROP TABLE dbo.[${testTable}]`);
      } finally {
        await mssqlDb.disconnect();
      }
    });

    it("escapeId, sort_builder, and where edge cases", function () {
      assert.strictEqual(mssqlDb.escapeId("users"), "[users]");
      assert.strictEqual(mssqlDb.escapeId("dbo.users"), "[dbo].[users]");
      assert.strictEqual(mssqlDb.escapeId("user]name"), "[user]]name]");

      assert.deepStrictEqual(mssqlDb.sort_builder(null), { query: "", value: [] });
      assert.strictEqual(mssqlDb.sort_builder(["+name", "-score"]).query, "ORDER BY [name] ASC,[score] DESC");

      assert.strictEqual(mssqlDb.where("invalid"), null);
      assert.deepStrictEqual(mssqlDb.where([]), { query: "", value: [] });

      const sd = mssqlDb.where([], "is_deleted");
      assert.ok(sd.query.includes("[is_deleted] = @param0"));
      assert.strictEqual(sd.value[0], 0);

      const w = mssqlDb.where([
        [
          ["name", "=", "MSSQL User"],
          ["score", ">", 10],
          ["score", "<", 100],
          ["score", "<=", 90],
          ["score", ">=", 20],
          ["score", "!=", 50],
          ["name", "like", "MSSQL"],
          ["name", "not like", "Test"],
          ["score", "in", [1, 2]],
          ["score", "not in", [3, 4]],
        ],
      ]);
      assert.ok(w.query.startsWith("WHERE (("));
      assert.strictEqual(mssqlDb.where([[["name", "INVALID_OP", "val"]]]), null);
      assert.strictEqual(mssqlDb.where([[["name", "in", "not-array"]]]), null);
    });

    it("CRUD operations: insert, list, get, qcount, upsert, remove", async function () {
      // 1. Single insert
      const insRes = await mssqlDb.insert(testTable, { name: "MSSQL Alice", score: 85 });
      assert.ok(insRes.id > 0);
      assert.strictEqual(insRes.rows, 1);
      const insertedId = insRes.id;

      // 2. Bulk insert
      const bulkRes = await mssqlDb.insert(testTable, [
        { name: "MSSQL Bob", score: 90 },
        { name: "MSSQL Charlie", score: 70 },
      ]);
      assert.strictEqual(bulkRes.rows, 2);

      // 3. Upsert
      const upRes = await mssqlDb.upsert(testTable, { id: insertedId, name: "MSSQL Alice Up", score: 95 }, ["id"]);
      assert.ok(upRes.rows >= 0);

      // 4. List
      const listRes = await mssqlDb.list(testTable, [[["score", ">=", 70]]], ["-score"], null, 0, 10);
      assert.ok(listRes.data.length >= 3);
      assert.strictEqual(listRes.count, 3);

      // 5. Get
      const getRes = await mssqlDb.get(testTable, [[["id", "=", insertedId]]]);
      assert.strictEqual(getRes.data.length, 1);

      // 6. Qcount
      const countRes = await mssqlDb.qcount(testTable, [[["score", ">=", 70]]]);
      assert.strictEqual(countRes, 3);

      // 7. Soft remove
      const softRem = await mssqlDb.remove(testTable, [[["id", "=", insertedId]]], "is_deleted");
      assert.ok(softRem.message.includes("removed"));

      // 8. Hard remove
      const hardRem = await mssqlDb.remove(testTable, [[["id", "=", insertedId]]]);
      assert.ok(hardRem.message.includes("removed"));

      // 9. Pure upsert (no unique keys)
      const pureUp = await mssqlDb.upsert(testTable, { name: "MSSQL Pure", score: 55 }, []);
      assert.strictEqual(pureUp.rows, 1);

      // 10. Merge insert via bulk insert with unique keys
      const mergeIns = await mssqlDb.insert(
        testTable,
        [
          { name: "MSSQL Batch 1", score: 11 },
          { name: "MSSQL Batch 2", score: 22 },
        ],
        ["name"],
      );
      assert.strictEqual(mergeIns.rows, 2);

      // Single insert with unique keys
      const singleMergeMssql = await mssqlDb.insert(
        testTable,
        { name: "MSSQL Single Merge", score: 33 },
        ["name"],
      );
      assert.strictEqual(singleMergeMssql.rows, 1);
      assert.ok(singleMergeMssql.id >= 0);
    });
  });
});
